#!/usr/bin/env bash
# tldt tree — create / list / remove parallel worktrees
set -euo pipefail

# shellcheck source=../../lib/common.sh
source "${TLDT_ROOT}/lib/common.sh"

usage() {
  cat <<EOF
Usage:
  tldt tree <name> [base-branch] [--remote|--local] [--no-open] [--no-install] [--no-dev]
  tldt tree --list
  tldt tree rm <name> [--force] [--delete-branch]
  tldt tree --help

Create a parallel git worktree with its own free-port dev server.

Arguments:
  name            Worktree + branch name (any git branch name; e.g. feature/login
                  or hotfix-auth). Slashes become '--' in the folder name.
  base-branch     Create from this branch when <name> is new (default: main,
                  or .tldt.json tree.defaultBase)

Flags:
  --remote        Fetch and use origin/<base-branch> (default)
  --local         Use your local <base-branch> as-is
  --no-open       Do not open an editor window
  --no-install    Skip dependency install
  --no-dev        Skip starting the dev server
  --list          List worktrees and server status
  rm              Remove a worktree (see tldt tree rm --help)
  -h, --help      Show this help

Examples:
  tldt tree feature/login
  tldt tree hotfix-auth main --local
  tldt tree feature/login origin-feature --remote
  tldt tree feature/login other-branch
  tldt tree --list
  tldt tree rm feature/login
  tldt tree rm feature/login --force --delete-branch

Environment / config:
  TLDT_EDITOR=cursor|code|none
  TLDT_DEFAULT_BASE, TLDT_DEV_CMD, TLDT_INSTALL_CMD, TLDT_COPY_ENV
  Per-repo: <repo>/.tldt.json  (see docs/tree.md)
EOF
}

resolve_start_point() {
  local base="$1" source="$2"
  if [[ "${source}" == "remote" ]]; then
    echo "→ Fetching origin/${base}…" >&2
    if ! git fetch origin "${base}"; then
      echo "Error: could not fetch origin/${base}" >&2
      exit 1
    fi
    if ! git show-ref --verify --quiet "refs/remotes/origin/${base}"; then
      echo "Error: origin/${base} not found after fetch" >&2
      exit 1
    fi
    echo "origin/${base}"
  else
    if ! git show-ref --verify --quiet "refs/heads/${base}"; then
      echo "Error: local branch '${base}' not found" >&2
      exit 1
    fi
    echo "${base}"
  fi
}

write_launcher_and_meta() {
  local dir="$1" name="$2" port="$3" dev_cmd="$4"
  local tldt_dir="${dir}/.tldt"
  mkdir -p "${tldt_dir}"

  cat >"${tldt_dir}/dev.sh" <<EOF
#!/usr/bin/env bash
# Auto-generated by tldt tree — local only, do not commit.
set -euo pipefail
cd "\$(dirname "\$0")/.."
export PORT="${port}"
echo "Starting ${name} on http://localhost:\${PORT}"
${dev_cmd}
EOF
  chmod +x "${tldt_dir}/dev.sh"

  cat >"${tldt_dir}/tree.json" <<EOF
{
  "name": "$(printf '%s' "${name}" | sed 's/"/\\"/g')",
  "port": ${port},
  "url": "http://localhost:${port}",
  "devCommand": "$(printf '%s' "${dev_cmd}" | sed 's/"/\\"/g')",
  "createdBy": "tldt tree",
  "createdAt": "$(date -u +"%Y-%m-%dT%H:%M:%SZ")"
}
EOF
}

list_worktrees() {
  local primary parent path branch bare name port status url meta
  primary="$(resolve_primary)"
  parent="$(dirname "${primary}")"
  cd "${primary}"

  printf "%-28s %-28s %-10s %s\n" "NAME" "BRANCH" "SERVER" "LOCATION"
  printf "%-28s %-28s %-10s %s\n" "----" "------" "------" "--------"

  path=""
  branch=""
  bare=""
  while IFS= read -r line || [[ -n "${line}" ]]; do
    if [[ -z "${line}" ]]; then
      if [[ -n "${path}" && -z "${bare}" ]]; then
        _print_row "${primary}" "${parent}" "${path}" "${branch}"
      fi
      path=""; branch=""; bare=""
      continue
    fi
    case "${line}" in
      worktree\ *) path="${line#worktree }" ;;
      branch\ *) branch="${line#branch refs/heads/}" ;;
      bare) bare=1 ;;
      detached) branch="(detached)" ;;
    esac
  done < <(git worktree list --porcelain; echo "")

  if [[ -n "${path}" && -z "${bare}" ]]; then
    _print_row "${primary}" "${parent}" "${path}" "${branch}"
  fi
}

_print_row() {
  local primary="$1" parent="$2" path="$3" branch="$4"
  local name port status url meta pid_file pid base prefix

  base="$(basename "${primary}")"
  prefix="${parent}/${base}-"

  if [[ "${path}" == "${primary}" ]]; then
    name="(primary)"
    port="3000"
  elif [[ "${path}" == "${prefix}"* ]]; then
    name="${path#"${prefix}"}"
    name="${name//--//}"
  else
    name="$(basename "${path}")"
  fi

  [[ -z "${branch}" ]] && branch="(unknown)"
  port=""
  status="stopped"
  url="—"
  meta="${path}/.tldt/tree.json"
  pid_file="${path}/.tldt/dev.pid"

  if [[ -f "${meta}" ]]; then
    port="$(node -e 'const j=require(process.argv[1]); if(j.port) console.log(j.port)' "${meta}" 2>/dev/null || true)"
    url="$(node -e 'const j=require(process.argv[1]); if(j.url) console.log(j.url)' "${meta}" 2>/dev/null || true)"
  fi

  pid=""
  if [[ -f "${pid_file}" ]]; then
    pid="$(tr -d '[:space:]' <"${pid_file}" || true)"
  fi

  if [[ -n "${port}" ]] && port_in_use "${port}"; then
    status="running"
    url="${url:-http://localhost:${port}}"
  elif [[ -n "${pid}" ]] && kill -0 "${pid}" 2>/dev/null; then
    status="starting"
    url="${url:-http://localhost:${port:-?}}"
  elif [[ "${path}" == "${primary}" ]]; then
    if port_in_use 3000; then
      status="running"
      url="http://localhost:3000"
    fi
  fi

  if [[ -n "${port}" && "${url}" == "—" ]]; then
    url="http://localhost:${port} (configured)"
  fi

  printf "%-28s %-28s %-10s %s\n" "${name}" "${branch}" "${status}" "${url}"
  printf "%-28s %-28s %-10s %s\n" "" "" "" "${path}"
}

remove_worktree() {
  local name="$1"
  shift
  local force=0 delete_branch=0
  local original_pwd primary worktree_dir worktree_real
  local pid_file meta port

  for arg in "$@"; do
    case "${arg}" in
      --force) force=1 ;;
      --delete-branch) delete_branch=1 ;;
      -h|--help)
        cat <<EOF
Usage: tldt tree rm <name> [--force] [--delete-branch]
EOF
        exit 0
        ;;
      *)
        echo "Error: unknown flag '${arg}'"
        exit 1
        ;;
    esac
  done

  original_pwd="$(pwd -P)"
  primary="$(resolve_primary)"
  worktree_dir="$(worktree_dir_for_slug "${name}")"

  if [[ -d "${worktree_dir}" ]]; then
    worktree_real="$(cd "${worktree_dir}" && pwd -P)"
    case "${original_pwd}" in
      "${worktree_real}"|"${worktree_real}"/*)
        echo "Error: you are inside ${worktree_dir}"
        echo "  cd to the primary checkout first:  cd ${primary}"
        exit 1
        ;;
    esac
  fi

  cd "${primary}"

  pid_file="${worktree_dir}/.tldt/dev.pid"
  meta="${worktree_dir}/.tldt/tree.json"
  if [[ -f "${pid_file}" ]]; then
    local pid
    pid="$(tr -d '[:space:]' <"${pid_file}" || true)"
    if [[ -n "${pid}" ]] && kill -0 "${pid}" 2>/dev/null; then
      echo "→ Stopping worktree dev server (pid ${pid})…"
      kill -TERM "-${pid}" 2>/dev/null || true
      kill_process_tree TERM "${pid}"
      sleep 0.5
      kill -KILL "-${pid}" 2>/dev/null || true
      kill_process_tree KILL "${pid}"
    fi
    rm -f "${pid_file}"
  fi
  if [[ -f "${meta}" ]]; then
    port="$(node -e 'const j=require(process.argv[1]); if(j.port) console.log(j.port)' "${meta}" 2>/dev/null || true)"
    if [[ -n "${port}" ]]; then
      echo "→ Ensuring port ${port} is free…"
      kill_port_listeners "${port}"
    fi
  fi

  if git worktree list --porcelain | awk -v dir="${worktree_dir}" '
    $1 == "worktree" && $2 == dir { found=1 }
    END { exit found ? 0 : 1 }
  '; then
    echo "→ Removing worktree ${worktree_dir}…"
    if [[ "${force}" -eq 1 ]]; then
      git worktree remove --force "${worktree_dir}"
    else
      if ! git worktree remove "${worktree_dir}"; then
        echo "Hint: commit/stash changes, or re-run with --force"
        exit 1
      fi
    fi
  elif [[ -e "${worktree_dir}" ]]; then
    echo "→ Path exists but is not a registered worktree; removing directory…"
    rm -rf "${worktree_dir}"
    git worktree prune
  else
    echo "→ No worktree found at ${worktree_dir}"
    git worktree prune
  fi

  if [[ "${delete_branch}" -eq 1 ]]; then
    if git show-ref --verify --quiet "refs/heads/${name}"; then
      if git worktree list --porcelain | awk -v b="refs/heads/${name}" '
        $1 == "branch" && $2 == b { found=1 }
        END { exit found ? 0 : 1 }
      '; then
        echo "Error: branch ${name} is still checked out in another worktree"
        exit 1
      fi
      echo "→ Deleting local branch ${name}…"
      git branch -D "${name}"
    else
      echo "→ Local branch ${name} not found (skipped)"
    fi
  fi

  echo
  echo "Done. Remaining worktrees:"
  git worktree list
}

# ---------- argv ----------
if [[ $# -lt 1 ]]; then
  usage
  exit 1
fi

# Delegate remove
if [[ "$1" == "rm" || "$1" == "remove" ]]; then
  shift
  if [[ $# -lt 1 ]]; then
    echo "Usage: tldt tree rm <name> [--force] [--delete-branch]"
    exit 1
  fi
  NAME="$1"
  shift
  remove_worktree "${NAME}" "$@"
  exit 0
fi

BRANCH=""
BASE_BRANCH=""
SOURCE="remote"
OPEN_EDITOR=1
DO_INSTALL=1
DO_DEV=1
DO_LIST=0
POSITIONALS=()

for arg in "$@"; do
  case "${arg}" in
    -h|--help) usage; exit 0 ;;
    --list) DO_LIST=1 ;;
    --remote) SOURCE="remote" ;;
    --local) SOURCE="local" ;;
    --no-open) OPEN_EDITOR=0 ;;
    --no-install) DO_INSTALL=0 ;;
    --no-dev) DO_DEV=0 ;;
    -*)
      echo "Error: unknown flag '${arg}'"
      usage
      exit 1
      ;;
    *) POSITIONALS+=("${arg}") ;;
  esac
done

load_repo_config
BASE_BRANCH="${BASE_BRANCH:-${TLDT_DEFAULT_BASE:-main}}"

if [[ "${DO_LIST}" -eq 1 ]]; then
  [[ ${#POSITIONALS[@]} -eq 0 ]] || { echo "Error: --list does not take a name"; exit 1; }
  list_worktrees
  exit 0
fi

if [[ ${#POSITIONALS[@]} -lt 1 || ${#POSITIONALS[@]} -gt 2 ]]; then
  usage
  exit 1
fi

BRANCH="${POSITIONALS[0]}"
if [[ ${#POSITIONALS[@]} -eq 2 ]]; then
  BASE_BRANCH="${POSITIONALS[1]}"
fi

if ! valid_branch_name "${BRANCH}"; then
  echo "Error: invalid name '${BRANCH}' (no spaces, leading dot, or '..')"
  exit 1
fi

PRIMARY="$(resolve_primary)"
cd "${PRIMARY}"
WORKTREE_DIR="$(worktree_dir_for_slug "${BRANCH}")"
ENV_SRC="${PRIMARY}/.env"

if [[ -e "${WORKTREE_DIR}" ]]; then
  echo "Error: path already exists: ${WORKTREE_DIR}"
  echo "Remove it first with:  tldt tree rm ${BRANCH}"
  exit 1
fi

BASED_ON=""
if git show-ref --verify --quiet "refs/heads/${BRANCH}"; then
  echo "→ Branch ${BRANCH} already exists locally — checking it out in the new worktree"
  echo "  (base-branch / --remote|--local ignored)"
  git worktree add "${WORKTREE_DIR}" "${BRANCH}"
  BASED_ON="existing local ${BRANCH}"
elif git show-ref --verify --quiet "refs/remotes/origin/${BRANCH}"; then
  echo "→ Branch ${BRANCH} exists on origin — creating local tracking branch"
  echo "  (base-branch / --remote|--local ignored)"
  git fetch origin "${BRANCH}"
  git worktree add --track -b "${BRANCH}" "${WORKTREE_DIR}" "origin/${BRANCH}"
  BASED_ON="existing origin/${BRANCH}"
else
  START_POINT="$(resolve_start_point "${BASE_BRANCH}" "${SOURCE}")"
  echo "→ Creating ${BRANCH} from ${START_POINT}…"
  git worktree add -b "${BRANCH}" "${WORKTREE_DIR}" "${START_POINT}"
  BASED_ON="${START_POINT} (--${SOURCE})"
fi

if [[ "${TLDT_COPY_ENV}" == "1" && -f "${ENV_SRC}" ]]; then
  echo "→ Copying .env…"
  cp "${ENV_SRC}" "${WORKTREE_DIR}/.env"
elif [[ "${TLDT_COPY_ENV}" == "1" ]]; then
  echo "→ No .env in primary (skipped)"
fi

PORT=""
DEV_CMD=""
URL=""
if [[ "${DO_DEV}" -eq 1 ]]; then
  PORT="$(find_free_port)"
  # detect_dev_command needs to run with cwd of worktree for package.json require — use pushd
  DEV_CMD="$(cd "${WORKTREE_DIR}" && detect_dev_command "${WORKTREE_DIR}" "${PORT}")"
  write_launcher_and_meta "${WORKTREE_DIR}" "${BRANCH}" "${PORT}" "${DEV_CMD}"
  URL="http://localhost:${PORT}"
  echo "→ Using port ${PORT}"
fi

if [[ "${DO_INSTALL}" -eq 1 ]]; then
  INSTALL_CMD="$(detect_install_command "${WORKTREE_DIR}")"
  if [[ -n "${INSTALL_CMD}" ]]; then
    echo "→ ${INSTALL_CMD}…"
    (cd "${WORKTREE_DIR}" && bash -lc "${INSTALL_CMD}")
  else
    echo "→ No package manager project detected (skipped install)"
  fi
fi

if [[ "${DO_DEV}" -eq 1 ]]; then
  LOG_FILE="${WORKTREE_DIR}/.tldt/dev.log"
  echo "→ Starting dev server (log: ${LOG_FILE})…"
  (
    cd "${WORKTREE_DIR}"
    export NVM_DIR="${NVM_DIR:-$HOME/.nvm}"
    # shellcheck disable=SC1091
    [[ -s "${NVM_DIR}/nvm.sh" ]] && . "${NVM_DIR}/nvm.sh"
    [[ -f .nvmrc ]] && nvm use >/dev/null 2>&1 || true
    PID="$(start_detached "${LOG_FILE}" "${WORKTREE_DIR}/.tldt/dev.sh")"
    echo "${PID}" >"${WORKTREE_DIR}/.tldt/dev.pid"
  )
fi

open_in_editor "${WORKTREE_DIR}" "${OPEN_EDITOR}"

echo
echo "Done."
echo "  Worktree: ${WORKTREE_DIR}"
echo "  Branch:   ${BRANCH}"
echo "  Based on: ${BASED_ON}"
if [[ -n "${URL}" ]]; then
  echo "  Dev URL:  ${URL}"
fi
echo
[[ "${DO_DEV}" -eq 1 ]] && echo "Restart later:  ${WORKTREE_DIR}/.tldt/dev.sh"
echo "Remove later:   tldt tree rm ${BRANCH}"
